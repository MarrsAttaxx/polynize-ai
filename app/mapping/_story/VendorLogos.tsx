/**
 * One mark, scaled into a `size` box centred on (x, y). Colour comes from the parent
 * via currentColor, so the caller decides how bright it sits in the panel.
 */
export function VendorLogo({
  name,
  x,
  y,
  size,
}: {
  name: VendorName;
  x: number;
  y: number;
  size: number;
}) {
  const [vx, vy, vw, vh] = ART[name].vb;
  const k = size / Math.max(vw, vh);
  return (
    <g
      transform={`translate(${x.toFixed(1)} ${y.toFixed(1)}) scale(${k.toFixed(4)}) translate(${(
        -(vx + vw / 2)
      ).toFixed(1)} ${(-(vy + vh / 2)).toFixed(1)})`}
      fill="currentColor"
    >
      {ART[name].body}
    </g>
  );
}
